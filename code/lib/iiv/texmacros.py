"""Writer for the numbers the prose quotes, as LaTeX macros (port of
app_numbers_v22.R). emit_app_numbers_tex() takes one dict per application with
the fitted quantities and writes tables/app_numbers.tex. Macros are named
\\App<Application><Quantity>; anything not supplied is written as \\textbf{??},
so an application that was not run shows a visible marker in the PDF.

Each application dict may hold:
  comparison: list of three dicts (OLS, IV, IIV) with estimate, se, ci_lower, ci_upper, n
  se_routes:  dict route -> se, routes containing 'naive', 'analytic', 'bootstrap'
  delta_hat, k_hat
  frontier:   list of dicts with status, cor_S_x, S_set_fraction, beta_lower, beta_upper, relevance_floor
  ols_gap:    dict with difference, se
  third_moments: dict mu30/mu21/mu12/mu03 -> (estimate, t)
sim: dict with sign_accuracy (list), n_samples (list), n_estimates (list).
"""
import os, math, datetime

NA = '\\textbf{??}'


def _f(v, d=3):
    return '??' if v is None or not math.isfinite(v) else ('%.' + str(d) + 'f') % v


def _n(v):
    return '??' if v is None or not math.isfinite(v) else '{:,}'.format(int(v)).replace(',', '{,}')


def _pc(v, d=0):
    return '??' if v is None or not math.isfinite(v) else ('%.' + str(d) + 'f') % (100 * v)


def one(x, stem):
    if x is None:
        return None
    cmp_ = x.get('comparison') or []; sr = x.get('se_routes') or {}; fr = x.get('frontier'); gap = x.get('ols_gap')
    pick = lambda col, i: cmp_[i].get(col) if len(cmp_) > i else None
    route = lambda pat: next((v for k, v in sr.items() if pat in k), None)
    ok = [r for r in (fr or []) if r.get('status') == 'ok']; bad = [r for r in (fr or []) if r.get('status') != 'ok']
    first = ok[0] if ok else {}
    rb, rn = route('bootstrap'), route('naive')
    out = dict(OLS=_f(pick('estimate', 0)), OLSSE=_f(pick('se', 0)), IV=_f(pick('estimate', 1)), IVSE=_f(pick('se', 1)),
               IIV=_f(pick('estimate', 2)), NaiveSE=_f(rn), AnalyticSE=_f(route('analytic')), BootSE=_f(rb),
               SERatio=_f(rb / rn if rb is not None and rn else None, 1), CILo=_f(pick('ci_lower', 2)),
               CIHi=_f(pick('ci_upper', 2)), N=_n(pick('n', 0)), NIV=_n(pick('n', 1)), NIIV=_n(pick('n', 2)),
               Delta=_f(x.get('delta_hat')), K='??' if x.get('k_hat') is None else '%+d' % int(x['k_hat']),
               CorSX=_f(first.get('cor_S_x')), SSet=_pc(first.get('S_set_fraction'), 0),
               IdLo=_f(first.get('beta_lower')), IdHi=_f(first.get('beta_upper')),
               Gap=_f(gap.get('difference') if gap else None), GapSE=_f(gap.get('se') if gap else None),
               FloorMax=_f(max(r['relevance_floor'] for r in ok) if ok else None, 2),
               FloorFail=_f(min(r['relevance_floor'] for r in bad) if fr and bad else None, 2))
    names = {'0': 'Zero', '1': 'One', '2': 'Two', '3': 'Three'}
    tm = x.get('third_moments') or {}
    for m in ('mu30', 'mu21', 'mu12', 'mu03'):
        lab = 'Mu' + ''.join(names[c] for c in m[2:]); est, t = tm.get(m, (None, None))
        out[lab] = _f(est, 4); out[lab + 'T'] = _f(t, 2)
    return {'App' + stem + k: v for k, v in out.items()}


def sim_macros(res):
    if res is None:
        return {}
    acc = res['sign_accuracy']
    return dict(SimSignAccuracy=_pc(min(acc), 1), SimSignAllCorrect='1' if all(a == 1 for a in acc) else '0',
                SimSamples=_n(sum(res['n_samples'])), SimEstimates=_n(sum(res['n_estimates'])))


def emit_app_numbers_tex(mroz=None, banerjee=None, card=None, sim=None, pension=None, file='app_numbers', dir='tables'):
    defs = {}
    for x, s in ((mroz, 'Mroz'), (banerjee, 'Banerjee'), (card, 'Card'), (pension, 'Pension')):
        defs.update(one(x, s) or {})
    defs.update(sim_macros(sim))
    template = [k[4:] for k in one({}, 'X')]
    for s in ('Mroz', 'Banerjee', 'Card', 'Pension'):
        for w in template:
            defs.setdefault('App' + s + w, NA)
    for w in ('SimSignAccuracy', 'SimSignAllCorrect', 'SimSamples', 'SimEstimates'):
        defs.setdefault(w, NA)
    os.makedirs(dir, exist_ok=True); path = os.path.join(dir, file + '.tex')
    with open(path, 'w') as fh:
        fh.write('%% generated by texmacros.py on %s\n' % datetime.datetime.now().strftime('%Y-%m-%d %H:%M'))
        fh.write('% Numbers quoted in the running text. Do NOT edit by hand.\n% \\textbf{??} marks an application that was not run.\n')
        fh.writelines('\\newcommand{\\%s}{%s}\n' % kv for kv in defs.items())
    print('  -> %s (%d macros)' % (path, len(defs)))
    return path
