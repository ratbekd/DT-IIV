"""LaTeX tables of Subsection S5.7 (sets between the one-sided and the CH sets) from the CSV files
written by simulations/sim_power.py and applications/power_apps.py.
Usage: python power_tables.py   ->  output/tables_power/tab_power_*.tex"""
import os, numpy as np, pandas as pd
import _setup

ROOT = os.path.join(_setup.HERE, '..', '..', 'output')
SIM = os.path.join(ROOT, 'simulations'); APP = os.path.join(ROOT, 'applications'); TAB = os.path.join(ROOT, 'tables_power')
os.makedirs(TAB, exist_ok=True)
f3 = lambda v: '---' if not np.isfinite(v) else '%.3f' % v
m3 = lambda v: '---' if not np.isfinite(v) else r'\(%.3f\)' % v
NAMES = {'Mroz': 'Mroz', 'Card': 'Card', 'STAR': 'STAR', 'Maimonides grade 5': 'Maimonides, grade 5',
         'Maimonides grade 4': 'Maimonides, grade 4', 'Banerjee-Iyer': 'Banerjee--Iyer', 'ADH': 'ADH'}


def short(app):
    return next(v for k, v in NAMES.items() if app.startswith(k))


def write(name, lines):
    with open(os.path.join(TAB, name + '.tex'), 'w') as fh:
        fh.write('% generated by power_tables.py\n' + '\n'.join(lines) + '\n')
    print('->', name)


def fmt_set(s):
    """'[a, b] U [c, d]b' -> LaTeX, two pieces stacked."""
    if s == 'empty':
        return r'\(\emptyset\)'
    parts = []
    for p in s.split(' U '):
        edge = p.endswith('b'); p = p.rstrip('b')
        a, b = p.strip('[]').split(', ')
        parts.append(r'[%s,\,%s]%s' % (a, b, r'^{\dagger}' if edge else ''))
    if len(parts) == 1:
        return r'\(%s\)' % parts[0]
    return r'\(\substack{%s}\)' % r'\\{}\cup'.join(parts)


# ---------------------------------------------------------------- simulations
def tab_bnd():
    d = pd.read_csv(os.path.join(SIM, 'sim_power_bnd.csv')); d = d[d.n == 1000]; L = []
    for c in d.c.unique():
        cells = []
        for h in sorted(d.het.unique()):
            r = d[(d.c == c) & (d.het == h)].iloc[0]; cells += [f3(r.cover), f3(r.power)]
        L.append('%s & %s \\\\' % (r'\(\infty\)' if np.isinf(c) else '%g' % c, ' & '.join(cells)))
    write('tab_power_bnd_mc', L)


def tab_apps_b(cs=(0.0, 0.05, 0.1, 0.2, np.inf)):
    d = pd.read_csv(os.path.join(APP, 'power_apps_bnd.csv')); L = []
    for app, g in d.groupby('app', sort=False):
        row = [short(app), m3(g.rho_s.iloc[0]), m3(g.rho_s2.iloc[0])]
        for c in cs:
            row.append(fmt_set(g[np.isclose(g.c, c) | (np.isinf(g.c) & np.isinf(c))].iloc[0].set))
        L.append(' & '.join(row) + r' \\')
    write('tab_power_apps_bnd', L)


def tab_breakdown():
    """Per application: sample correlations, the sets at c = 0 and c = inf, the smallest
    bound with a nonempty set, and the breakdown values for zero, OLS and 2SLS."""
    d = pd.read_csv(os.path.join(APP, 'power_apps_bnd.csv')); k = pd.read_csv(os.path.join(APP, 'power_apps_breakdown.csv'))
    cv = lambda v: r'\(\infty\)' if np.isinf(v) else ('0' if v == 0 else '%.3f' % v)
    L = []
    for app, g in d.groupby('app', sort=False):
        r = k[k.app == app].iloc[0]
        ch = fmt_set(g[g.c == 0].iloc[0].set); os_ = fmt_set(g[np.isinf(g.c)].iloc[0].set)
        L.append(' & '.join([short(app), m3(g.rho_s.iloc[0]), m3(g.rho_s2.iloc[0]), ch, os_, cv(r.c_min),
                             cv(r.c_zero), cv(r.c_ols), cv(r.c_tsls)]) + r' \\')
    write('tab_power_breakdown', L)


if __name__ == '__main__':
    for f in (tab_bnd, tab_apps_b, tab_breakdown):
        try:
            f()
        except FileNotFoundError as e:
            print('skipped', f.__name__, e)
